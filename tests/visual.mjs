import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = []; page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(process.env.BASE_URL || 'http://127.0.0.1:5173', { waitUntil: 'networkidle' });
  await page.locator('.loader').waitFor({ state: 'hidden' });
  assert.equal(await page.locator('.world-fallback').count(), 0);
  await page.waitForTimeout(350); await page.screenshot({ path: '/tmp/glance-hero.png' });
  const scroll = async value => { await page.evaluate(p => window.scrollTo({ top: (document.querySelector('.experience-scroll').offsetHeight - innerHeight) * p, behavior: 'instant' }), value); await page.waitForTimeout(500); };
  assert.equal(await page.locator('.rotation-controls').count(), 0);
  await scroll(.1);
  assert.equal(await page.locator('.experience-viewport .wordmark').count(), 1, 'Only the original fading logo appears during entry');
  assert.ok(Number(await page.locator('.site-nav').evaluate(e => getComputedStyle(e).opacity)) < 1);
  await scroll(.58); await page.waitForTimeout(350); await page.screenshot({ path: '/tmp/glance-lens.png' });
  await scroll(.84); await page.waitForTimeout(350); await page.screenshot({ path: '/tmp/glance-entry.png' });
  await page.getByRole('button', { name: 'Skip transition', exact: true }).click();
  await page.locator('.pov-ui').waitFor();
  await page.waitForTimeout(350); await page.screenshot({ path: '/tmp/glance-pov.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(600);
  assert.ok(Math.abs(await page.locator('.experience-viewport').evaluate(e => e.getBoundingClientRect().top)) < 2, 'Open demo stays in view after resize');
  await page.waitForTimeout(350); await page.screenshot({ path: '/tmp/glance-mobile-active.png' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.waitForTimeout(600);
  await page.getByRole('button', { name: 'Find next item', exact: true }).click();
  await page.locator('.floor-route').waitFor();
  await page.screenshot({ path: '/tmp/glance-route.png' });
  await page.getByRole('button', { name: 'Skip ahead', exact: true }).click();
  await page.getByRole('button', { name: 'Exit experience', exact: true }).click();
  await page.getByRole('button', { name: 'Enter the experience', exact: true }).click();
  await page.locator('.pov-ui').waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.pov-ui').count(), 0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(350); await page.screenshot({ path: '/tmp/glance-mobile.png' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.deepEqual(errors, []);
  const fallback = await browser.newPage();
  await fallback.addInitScript(() => { const original = HTMLCanvasElement.prototype.getContext; HTMLCanvasElement.prototype.getContext = function(type, ...args) { return /webgl/.test(type) ? null : original.call(this, type, ...args); }; });
  await fallback.goto(process.env.BASE_URL || 'http://127.0.0.1:5173');
  await fallback.locator('.world-fallback').waitFor();
  await fallback.getByRole('button', { name: 'Enter the experience', exact: true }).click();
  await fallback.locator('.pov-ui').waitFor();
  await fallback.getByRole('button', { name: 'Select original energy drink', exact: true }).click();
  await fallback.getByRole('button', { name: 'Add to cart', exact: true }).click();
  assert.equal(await fallback.locator('.cart-count').innerText(), '1');
  console.log('PASS: WebGL hero, scroll lens preview, click entry, Escape return, mobile width, and functional no-WebGL fallback. Screenshots: /tmp/glance-*.png');
} finally { await browser.close(); }
